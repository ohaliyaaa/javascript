console.log(2 > 1);
console.log(2 >= 1);
console.log(2 < 1);
console.log(2 == 1);
console.log(2 != 1);

console.log("2" > 1);
console.log("02" > 1);

console.log(null > 0);
console.log(null == 0);
console.log(null >= 0); // null converted into zero

console.log(undefined == 0);
console.log(undefined > 0);
console.log(undefined < 0);

// comparison and equality check are different in javascript.
// === -> strict check
console.log(undefined === 0);
